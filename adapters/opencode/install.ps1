# Installs the OpenCode adapter: a v2 plugin that injects memory + the knowledge
# map into every model request.
#
# The implementation stays in this repository (adapters/opencode/knowledge-index.js);
# the installed file is a shim, so `git pull` updates the behaviour.
param(
  [string]$PluginsDir = (Join-Path $env:USERPROFILE '.config\opencode\plugins')
)

$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$impl = Join-Path $repo 'adapters\opencode\knowledge-index.js'
if (-not (Test-Path $impl)) { throw "adapter not found: $impl" }
$uri = 'file:///' + ($impl -replace '\\', '/' -replace ' ', '%20')

New-Item -ItemType Directory -Force -Path $PluginsDir | Out-Null
$target = Join-Path $PluginsDir 'knowledge-index.ts'
if (Test-Path $target) {
  $bak = "$target.bak-" + (Get-Date -Format 'yyyyMMdd-HHmmss')
  Copy-Item $target $bak -Force
  Write-Host "backed up: $bak"
}

$shim = @"
// Generated by $repo\adapters\opencode\install.ps1
// Implementation: $impl
import { Plugin } from "@opencode/plugin"
import { buildContext, log } from "$uri"

export default Plugin.define({
  id: "local.knowledge-index",
  async setup(ctx) {
    await ctx.session.hook("context", async (event) => {
      try {
        const text = buildContext()
        if (!text) return
        event.system.push({ type: "text", text })
        log(``v2 injected session=`` + event.sessionID + `` chars=`` + text.length)
      } catch (error) {
        log(``v2 error session=`` + event.sessionID + ``: `` + String(error))
      }
    })
  },
})
"@
Set-Content -Path $target -Value $shim -Encoding utf8
Write-Host "installed: $target"
Write-Host "verify: run a prompt, then read the injection log at `$env:TEMP\kb-inject.log"
