# Installs the OpenCode adapter: a v2 plugin that injects memory + the knowledge
# map into every model request.
#
# The implementation stays in this repository (adapters/opencode/knowledge-index.js);
# the installed file is a shim, so `git pull` updates the behaviour.
param(
  [string]$PluginsDir = (Join-Path $env:USERPROFILE '.config\opencode\plugins')
)

$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$impl = Join-Path $repo 'adapters\opencode\knowledge-index.js'
if (-not (Test-Path $impl)) { throw "adapter not found: $impl" }
$uri = 'file:///' + ($impl -replace '\\', '/' -replace ' ', '%20')

New-Item -ItemType Directory -Force -Path $PluginsDir | Out-Null
$target = Join-Path $PluginsDir 'knowledge-index.ts'
if (Test-Path $target) {
  $bak = "$target.bak-" + (Get-Date -Format 'yyyyMMdd-HHmmss')
  Copy-Item $target $bak -Force
  Write-Host "backed up: $bak"
}

$shim = @"
// Generated by $repo\adapters\opencode\install.ps1
// Implementation: $impl
import { Plugin } from "@opencode/plugin"
import { buildContext, captureCandidate, log } from "$uri"

// Session -> workspace directory. The server process runs as a service, so
// process.cwd() is not the workspace; the session record is the only reliable
// source. Cached because it does not change for the life of a session.
const dirs = new Map<string, string>()

export default Plugin.define({
  id: "local.knowledge-index",
  async setup(ctx) {
    await ctx.session.hook("context", async (event) => {
      try {
        captureCandidate(event.messages, event.sessionID)
        let directory = dirs.get(event.sessionID) ?? ""
        if (!directory) {
          try {
            const session: any = await ctx.session.get({ sessionID: event.sessionID })
            directory = String(session?.location?.directory ?? "")
            if (directory) dirs.set(event.sessionID, directory)
          } catch {
            /* keep the cwd fallback */
          }
        }
        const text = buildContext(directory || undefined)
        if (!text) return
        // Ephemeral cache hint: the block is identical between turns and after
        // compaction, so the provider can reuse it instead of re-billing it.
        event.system.push({ type: "text", text, cache: { type: "ephemeral" } })
        log(``v2 injected session=`` + event.sessionID + `` dir=`` + directory + `` chars=`` + text.length)
      } catch (error) {
        log(``v2 error session=`` + event.sessionID + ``: `` + String(error))
      }
    })
  },
})
"@
[IO.File]::WriteAllText($target, $shim, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "installed: $target"

# AGENTS.md is generated from this repository too, so a wiped config comes back
# from here rather than from memory.
$configDir = Split-Path $PluginsDir -Parent
$agentsSource = Join-Path $repo 'adapters\opencode\AGENTS.md'
$agentsTarget = Join-Path $configDir 'AGENTS.md'
if (Test-Path $agentsSource) {
  if (Test-Path $agentsTarget) {
    $bak = "$agentsTarget.bak-" + (Get-Date -Format 'yyyyMMdd-HHmmss')
    Copy-Item $agentsTarget $bak -Force
    Write-Host "backed up: $bak"
  }
  Copy-Item $agentsSource $agentsTarget -Force
  Write-Host "installed: $agentsTarget"
}

# MCP tools live in opencode.jsonc, which this repository does not own: check the
# entry and print the canonical block when it is missing.
$config = Join-Path $configDir 'opencode.jsonc'
$snippet = Join-Path $repo 'adapters\opencode\mcp.ai-memory.jsonc'
if (Test-Path $config) {
  if ((Get-Content $config -Raw) -match '"ai-memory"') {
    Write-Host "ok: ai-memory MCP entry present in $config"
  } else {
    Write-Host "MISSING: add this block to mcp.servers in $config" -ForegroundColor Yellow
    if (Test-Path $snippet) { Write-Host (Get-Content $snippet -Raw) }
  }
}
Write-Host "verify: run a prompt, then read the injection log at `$env:TEMP\kb-inject.log"
